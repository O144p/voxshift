const WASM_SIMD_PROBE = new Uint8Array([
  0, 97, 115, 109, 1, 0, 0, 0, 1, 5, 1, 96, 0, 1, 123, 3, 2, 1, 0, 10, 10, 1,
  8, 0, 65, 0, 253, 15, 253, 98, 11,
])

export function isWasmSimdSupported(): boolean {
  try {
    return (
      typeof WebAssembly === 'object' && WebAssembly.validate(WASM_SIMD_PROBE)
    )
  } catch {
    return false
  }
}

export type ExportStage =
  | 'idle'
  | 'loading-core'
  | 'extracting-audio'
  | 'pitch-shifting'
  | 'muxing-mp4'
  | 'completed'
  | 'error'

export interface ExportProgress {
  stage: ExportStage
  stageLabel: string
  /** Overall export percentage (0..100) */
  overallPercent: number
  /** Current stage percentage (0..100) */
  stagePercent: number
  detail: string
  outputFileName?: string
  error?: string
}

export interface ExportJobOptions {
  file: File
  semitones: number
  cents: number
  formantCompensation: boolean
  onProgress?: (progress: ExportProgress) => void
  signal?: AbortSignal
}

/**
 * Formats the exported MP4 filename according to specification:
 * `<OriginalName>_[+2st].mp4` (or `[-2st]`, `[0st]`, `[+2st+15ct]`, etc.)
 */
export function formatExportFileName(
  originalName: string,
  semitones: number,
  cents = 0,
): string {
  const baseName = originalName.replace(/\.[^/.]+$/, '') || 'Karaoke_Track'
  const stPrefix = semitones > 0 ? `+${semitones}st` : `${semitones}st`
  const ctSuffix =
    cents !== 0 ? (cents > 0 ? `+${cents}ct` : `${cents}ct`) : ''
  return `${baseName}_[${stPrefix}${ctSuffix}].mp4`
}

interface DecodedPcmData {
  sampleRate: number
  numChannels: number
  numSamples: number
  channels: Float32Array[]
}

/**
 * Fast, low-memory parser for standard 16-bit PCM RIFF WAV generated by FFmpeg (`-c:a pcm_s16le`).
 * Falls back to Web Audio `decodeAudioData` if non-standard WAV chunks are encountered.
 */
async function decodeExtractedWav(wavBytes: Uint8Array): Promise<DecodedPcmData> {
  const view = new DataView(
    wavBytes.buffer,
    wavBytes.byteOffset,
    wavBytes.byteLength,
  )

  const readFourCC = (offset: number): string =>
    String.fromCharCode(
      view.getUint8(offset),
      view.getUint8(offset + 1),
      view.getUint8(offset + 2),
      view.getUint8(offset + 3),
    )

  if (
    wavBytes.byteLength >= 44 &&
    readFourCC(0) === 'RIFF' &&
    readFourCC(8) === 'WAVE'
  ) {
    let offset = 12
    let audioFormat = 0
    let numChannels = 0
    let sampleRate = 0
    let bitsPerSample = 0
    let dataOffset = -1
    let dataLength = 0

    while (offset + 8 <= wavBytes.byteLength) {
      const chunkId = readFourCC(offset)
      const chunkSize = view.getUint32(offset + 4, true)
      const chunkDataStart = offset + 8

      if (chunkId === 'fmt ' && chunkSize >= 16) {
        audioFormat = view.getUint16(chunkDataStart, true)
        numChannels = view.getUint16(chunkDataStart + 2, true)
        sampleRate = view.getUint32(chunkDataStart + 4, true)
        bitsPerSample = view.getUint16(chunkDataStart + 14, true)
      } else if (chunkId === 'data') {
        dataOffset = chunkDataStart
        dataLength = Math.min(chunkSize, wavBytes.byteLength - chunkDataStart)
        break
      }

      // Word-aligned chunk stepping
      offset = chunkDataStart + chunkSize + (chunkSize & 1)
    }

    if (
      audioFormat === 1 &&
      bitsPerSample === 16 &&
      numChannels > 0 &&
      sampleRate > 0 &&
      dataOffset >= 0 &&
      dataLength > 0
    ) {
      const bytesPerFrame = numChannels * 2
      const numSamples = Math.floor(dataLength / bytesPerFrame)
      const channels = Array.from(
        { length: numChannels },
        () => new Float32Array(numSamples),
      )

      let ptr = dataOffset
      for (let i = 0; i < numSamples; i++) {
        for (let ch = 0; ch < numChannels; ch++) {
          const sampleInt16 = view.getInt16(ptr, true)
          channels[ch][i] = sampleInt16 / 32768
          ptr += 2
        }
      }

      return {
        sampleRate,
        numChannels,
        numSamples,
        channels,
      }
    }
  }

  // Fallback to native Web Audio decodeAudioData
  const tempCtx = new OfflineAudioContext(2, 1, 44100)
  const copyBuffer = wavBytes.slice().buffer
  const audioBuffer = await tempCtx.decodeAudioData(copyBuffer)
  const channels: Float32Array[] = []
  for (let ch = 0; ch < audioBuffer.numberOfChannels; ch++) {
    channels.push(new Float32Array(audioBuffer.getChannelData(ch)))
  }

  return {
    sampleRate: audioBuffer.sampleRate,
    numChannels: audioBuffer.numberOfChannels,
    numSamples: audioBuffer.length,
    channels,
  }
}

/**
 * Encodes a rendered Web Audio `AudioBuffer` into an uncompressed 16-bit PCM WAV (`Uint8Array`).
 */
function encodeAudioBufferToWav(audioBuffer: AudioBuffer): Uint8Array {
  const numChannels = audioBuffer.numberOfChannels
  const sampleRate = audioBuffer.sampleRate
  const numSamples = audioBuffer.length
  const bytesPerSample = 2
  const blockAlign = numChannels * bytesPerSample
  const dataSize = numSamples * blockAlign
  const arrayBuffer = new ArrayBuffer(44 + dataSize)
  const view = new DataView(arrayBuffer)

  const writeStr = (offset: number, str: string) => {
    for (let i = 0; i < str.length; i++) {
      view.setUint8(offset + i, str.charCodeAt(i))
    }
  }

  writeStr(0, 'RIFF')
  view.setUint32(4, 36 + dataSize, true)
  writeStr(8, 'WAVE')
  writeStr(12, 'fmt ')
  view.setUint32(16, 16, true) // Subchunk1Size (16 for PCM)
  view.setUint16(20, 1, true) // AudioFormat (1 = PCM)
  view.setUint16(22, numChannels, true)
  view.setUint32(24, sampleRate, true)
  view.setUint32(28, sampleRate * blockAlign, true)
  view.setUint16(32, blockAlign, true)
  view.setUint16(34, 16, true) // BitsPerSample
  writeStr(36, 'data')
  view.setUint32(40, dataSize, true)

  const channelData: Float32Array[] = []
  for (let ch = 0; ch < numChannels; ch++) {
    channelData.push(audioBuffer.getChannelData(ch))
  }

  let offset = 44
  for (let i = 0; i < numSamples; i++) {
    for (let ch = 0; ch < numChannels; ch++) {
      const sample = Math.max(-1, Math.min(1, channelData[ch][i]))
      const int16 = sample < 0 ? sample * 32768 : sample * 32767
      view.setInt16(offset, Math.round(int16), true)
      offset += 2
    }
  }

  return new Uint8Array(arrayBuffer)
}

function uint8ArrayToBase64(bytes: Uint8Array): string {
  const chunkSize = 0x8000
  const chunks: string[] = []
  for (let i = 0; i < bytes.length; i += chunkSize) {
    const sub = bytes.subarray(i, i + chunkSize)
    chunks.push(String.fromCharCode(...sub))
  }
  return btoa(chunks.join(''))
}

async function saveOrShareMp4(
  mp4Bytes: Uint8Array,
  fileName: string,
): Promise<void> {
  if (Capacitor.isNativePlatform()) {
    const base64Data = uint8ArrayToBase64(mp4Bytes)
    const writeResult = await Filesystem.writeFile({
      path: fileName,
      data: base64Data,
      directory: Directory.Cache,
    })

    await Share.share({
      title: fileName,
      url: writeResult.uri,
      files: [writeResult.uri],
      dialogTitle: 'Enregistrer ou partager le MP4 transposé',
    })
    return
  }

  const mp4Blob = new Blob([mp4Bytes.slice()], { type: 'video/mp4' })
  const downloadUrl = URL.createObjectURL(mp4Blob)
  const anchor = document.createElement('a')
  anchor.href = downloadUrl
  anchor.download = fileName
  anchor.style.display = 'none'
  document.body.appendChild(anchor)
  anchor.click()
  document.body.removeChild(anchor)

  // Revoke object URL after download initiation so large MP4 blobs don't leak RAM
  setTimeout(() => {
    URL.revokeObjectURL(downloadUrl)
  }, 5000)
}

export class ExportPipeline {
  private ffmpeg: FFmpeg | null = null
  private loadPromise: Promise<FFmpeg> | null = null

  /**
   * Lazily loads the single-threaded `@ffmpeg/core` WebAssembly core (`ffmpeg-core.js`
   * and `ffmpeg-core.wasm`) directly from local bundled assets. Detects WebAssembly SIMD
   * support at runtime and falls back to `public/ffmpeg-nosimd/` on older CPUs.
   */
  private async ensureFFmpegLoaded(
    onProgress?: (progress: ExportProgress) => void,
    signal?: AbortSignal,
  ): Promise<FFmpeg> {
    if (this.ffmpeg && this.ffmpeg.loaded) {
      return this.ffmpeg
    }

    if (this.loadPromise) {
      return this.loadPromise
    }

    this.loadPromise = (async () => {
      const simdSupported = isWasmSimdSupported()

      onProgress?.({
        stage: 'loading-core',
        stageLabel: 'Initialisation du cœur FFmpeg',
        overallPercent: 3,
        stagePercent: 25,
        detail: simdSupported
          ? 'Chargement du module WebAssembly local @ffmpeg/core (SIMD)...'
          : 'Chargement du module WebAssembly local @ffmpeg/core (mode compatible sans SIMD)...',
      })

      const ffmpeg = new FFmpeg()
      const simdCoreJsUrl = new URL(coreJsUrl, window.location.href).href
      const simdCoreWasmUrl = new URL(coreWasmUrl, window.location.href).href
      const noSimdCoreJsUrl = new URL(
        './ffmpeg-nosimd/ffmpeg-core.js',
        window.location.href,
      ).href
      const noSimdCoreWasmUrl = new URL(
        './ffmpeg-nosimd/ffmpeg-core.wasm',
        window.location.href,
      ).href

      if (simdSupported) {
        try {
          await ffmpeg.load(
            {
              coreURL: simdCoreJsUrl,
              wasmURL: simdCoreWasmUrl,
            },
            { signal },
          )
        } catch (err) {
          const msg = err instanceof Error ? err.message : String(err)
          if (msg.includes('SIMD') || msg.includes('CompileError')) {
            await ffmpeg.load(
              {
                coreURL: noSimdCoreJsUrl,
                wasmURL: noSimdCoreWasmUrl,
              },
              { signal },
            )
          } else {
            throw err
          }
        }
      } else {
        await ffmpeg.load(
          {
            coreURL: noSimdCoreJsUrl,
            wasmURL: noSimdCoreWasmUrl,
          },
          { signal },
        )
      }

      this.ffmpeg = ffmpeg
      return ffmpeg
    })()

    try {
      return await this.loadPromise
    } catch (err) {
      this.loadPromise = null
      throw err
    }
  }

  /**
   * Runs the full offline MP4 export pipeline:
   * 1. Extract Audio -> Uncompressed PCM WAV
   * 2. Offline Maximum-Quality Pitch Shift via `signalsmith-stretch`
   * 3. Remux Original Video Stream (`-c:v copy`) + Pitch-Shifted Audio (`-c:a aac -b:a 192k`)
   * 4. Trigger Browser Download (`<OriginalName>_[+2st].mp4`) + Virtual FS & Blob Cleanup
   */
  public async exportTransposedMp4(options: ExportJobOptions): Promise<string> {
    const {
      file,
      semitones,
      cents,
      formantCompensation,
      onProgress,
      signal,
    } = options

    const outputDownloadName = formatExportFileName(file.name, semitones, cents)
    const jobId = Date.now()
    const extMatch = file.name.match(/\.[^/.]+$/)
    const inputExt = extMatch ? extMatch[0].toLowerCase() : '.mp4'

    const inputFsName = `input_${jobId}${inputExt}`
    const extractedWavFsName = `extracted_${jobId}.wav`
    const shiftedWavFsName = `shifted_${jobId}.wav`
    const outputMp4FsName = `output_${jobId}.mp4`

    const ffmpeg = await this.ensureFFmpegLoaded(onProgress, signal)

    let currentPhase: 'extracting' | 'muxing' | 'none' = 'none'
    const progressHandler = ({ progress }: { progress: number }) => {
      const clamped = Math.max(0, Math.min(1, Number.isFinite(progress) ? progress : 0))
      const stagePct = Math.round(clamped * 100)
      if (currentPhase === 'extracting') {
        onProgress?.({
          stage: 'extracting-audio',
          stageLabel: 'Extraction audio',
          overallPercent: Math.round(5 + clamped * 25),
          stagePercent: stagePct,
          detail: `Décodage de la piste audio source en WAV PCM non compressé (${stagePct}%)...`,
        })
      } else if (currentPhase === 'muxing') {
        onProgress?.({
          stage: 'muxing-mp4',
          stageLabel: 'Multiplexage MP4',
          overallPercent: Math.round(75 + clamped * 23),
          stagePercent: stagePct,
          detail: `Copie directe du flux vidéo (-c:v copy) et encodage audio AAC 192k (${stagePct}%)...`,
        })
      }
    }

    ffmpeg.on('progress', progressHandler)

    try {
      // ======================================================================
      // STEP 1: EXTRACT AUDIO TO UNCOMPRESSED PCM WAV
      // ======================================================================
      onProgress?.({
        stage: 'extracting-audio',
        stageLabel: 'Extraction audio',
        overallPercent: 5,
        stagePercent: 0,
        detail: `Chargement de « ${file.name} » dans le système de fichiers virtuel FFmpeg...`,
      })

      const sourceBytes = await fetchFile(file)
      await ffmpeg.writeFile(inputFsName, sourceBytes, { signal })

      currentPhase = 'extracting'
      const extractExitCode = await ffmpeg.exec(
        [
          '-i',
          inputFsName,
          '-vn',
          '-c:a',
          'pcm_s16le',
          extractedWavFsName,
        ],
        -1,
        { signal },
      )
      currentPhase = 'none'

      if (extractExitCode !== 0) {
        throw new Error(
          `Échec de l'extraction de la piste audio par FFmpeg (code ${extractExitCode}).`,
        )
      }

      const extractedFileData = await ffmpeg.readFile(
        extractedWavFsName,
        'binary',
        { signal },
      )
      // Free extracted WAV from FFmpeg FS immediately after reading into JS
      await this.safeDeleteFile(ffmpeg, extractedWavFsName)

      if (!(extractedFileData instanceof Uint8Array)) {
        throw new Error('Format de données inattendu lors de la lecture du WAV extrait.')
      }

      // ======================================================================
      // STEP 2: OFFLINE MAXIMUM-QUALITY PITCH SHIFT VIA SIGNALSMITH-STRETCH
      // ======================================================================
      onProgress?.({
        stage: 'pitch-shifting',
        stageLabel: 'Transposition',
        overallPercent: 32,
        stagePercent: 5,
        detail: 'Préparation du moteur DSP polyphonique hors-ligne Signalsmith Stretch...',
      })

      const decoded = await decodeExtractedWav(extractedFileData)
      const { sampleRate, numChannels, numSamples, channels } = decoded
      const durationSeconds = numSamples / sampleRate
      const totalSemitones = Number((semitones + cents / 100).toFixed(4))

      let shiftedWavBytes: Uint8Array

      if (totalSemitones === 0 && !formantCompensation) {
        // 0 semitones & 0 cents: preserve bit-exact original PCM audio
        onProgress?.({
          stage: 'pitch-shifting',
          stageLabel: 'Transposition',
          overallPercent: 72,
          stagePercent: 100,
          detail: 'Diapason 0 dt sélectionné — conservation de l’audio PCM d’origine...',
        })
        shiftedWavBytes = extractedFileData
      } else {
        const offlineCtx = new OfflineAudioContext(
          numChannels,
          numSamples,
          sampleRate,
        )

        const stretchNode = await SignalsmithStretch(offlineCtx, {
          numberOfInputs: 0,
          numberOfOutputs: 1,
          outputChannelCount: [numChannels],
        })

        // Maximum offline quality configuration: longer STFT window & tight overlap
        await stretchNode.configure({
          blockMs: 120,
          intervalMs: 24,
          splitComputation: false,
        })

        // Stream live progress updates from the AudioWorklet during offline render
        await stretchNode.setUpdateInterval(0.2, (inputTime: number) => {
          if (durationSeconds <= 0) return
          const ratio = Math.max(0, Math.min(1, inputTime / durationSeconds))
          const pct = Math.round(ratio * 100)
          onProgress?.({
            stage: 'pitch-shifting',
            stageLabel: 'Transposition',
            overallPercent: Math.round(32 + ratio * 40),
            stagePercent: pct,
            detail: `Transposition polyphonique hors-ligne (${totalSemitones > 0 ? `+${totalSemitones}` : totalSemitones} dt${formantCompensation ? ', Formants verrouillés' : ''}) — ${pct}%`,
          })
        })

        // Load full channel buffers and schedule exact 1:1 duration render (rate: 1.0)
        await stretchNode.addBuffers(channels)
        await stretchNode.schedule({
          output: 0,
          input: 0,
          active: true,
          rate: 1.0,
          semitones: totalSemitones,
          tonalityHz: 8000,
          formantCompensation,
          formantSemitones: 0,
        })

        stretchNode.connect(offlineCtx.destination)

        const renderedBuffer = await offlineCtx.startRendering()

        // Release worklet buffers immediately
        await stretchNode.dropBuffers()
        stretchNode.disconnect()

        onProgress?.({
          stage: 'pitch-shifting',
          stageLabel: 'Transposition',
          overallPercent: 73,
          stagePercent: 100,
          detail: 'Encodage de l’audio transposé en WAV PCM 16-bit...',
        })

        shiftedWavBytes = encodeAudioBufferToWav(renderedBuffer)
      }

      // ======================================================================
      // STEP 3: REMUX ORIGINAL VIDEO STREAM WITH PITCH-SHIFTED AUDIO
      // ======================================================================
      onProgress?.({
        stage: 'muxing-mp4',
        stageLabel: 'Multiplexage MP4',
        overallPercent: 75,
        stagePercent: 0,
        detail: 'Écriture de l’audio transposé et multiplexage du conteneur MP4...',
      })

      await ffmpeg.writeFile(shiftedWavFsName, shiftedWavBytes, { signal })

      currentPhase = 'muxing'
      const muxExitCode = await ffmpeg.exec(
        [
          '-i',
          inputFsName,
          '-i',
          shiftedWavFsName,
          '-map',
          '0:v:0?',
          '-map',
          '1:a:0',
          '-c:v',
          'copy',
          '-c:a',
          'aac',
          '-b:a',
          '192k',
          '-movflags',
          '+faststart',
          '-shortest',
          outputMp4FsName,
        ],
        -1,
        { signal },
      )
      currentPhase = 'none'

      if (muxExitCode !== 0) {
        throw new Error(
          `Échec du multiplexage MP4 par FFmpeg (code ${muxExitCode}).`,
        )
      }

      // Free input and intermediate WAV before reading final MP4 to minimize peak RAM
      await this.safeDeleteFile(ffmpeg, inputFsName)
      await this.safeDeleteFile(ffmpeg, shiftedWavFsName)

      const mp4Data = await ffmpeg.readFile(outputMp4FsName, 'binary', {
        signal,
      })
      await this.safeDeleteFile(ffmpeg, outputMp4FsName)

      if (!(mp4Data instanceof Uint8Array)) {
        throw new Error('Format de sortie inattendu lors de la lecture du MP4 multiplexé.')
      }

      await saveOrShareMp4(mp4Data, outputDownloadName)

      onProgress?.({
        stage: 'completed',
        stageLabel: 'Export terminé',
        overallPercent: 100,
        stagePercent: 100,
        detail: `Enregistré sous ${outputDownloadName}`,
        outputFileName: outputDownloadName,
      })

      return outputDownloadName
    } catch (err) {
      const message =
        err instanceof Error ? err.message : 'Échec de l’export MP4 hors-ligne.'
      onProgress?.({
        stage: 'error',
        stageLabel: 'Échec de l’export',
        overallPercent: 0,
        stagePercent: 0,
        detail: message,
        error: message,
      })
      throw err
    } finally {
      ffmpeg.off('progress', progressHandler)
      // Always clean up virtual FS files so large karaoke videos never leak RAM
      await this.safeDeleteFile(ffmpeg, inputFsName)
      await this.safeDeleteFile(ffmpeg, extractedWavFsName)
      await this.safeDeleteFile(ffmpeg, shiftedWavFsName)
      await this.safeDeleteFile(ffmpeg, outputMp4FsName)
    }
  }

  private async safeDeleteFile(ffmpeg: FFmpeg, path: string): Promise<void> {
    try {
      await ffmpeg.deleteFile(path)
    } catch {
      // Ignore if file was already deleted or not created
    }
  }

  public dispose(): void {
    if (this.ffmpeg) {
      this.ffmpeg.terminate()
      this.ffmpeg = null
    }
    this.loadPromise = null
  }
}
